function normalizeLanguage(language) {
  return (language || 'en').split('-')[0] === 'fr' ? 'fr' : 'en';
}

function resolveRouteKey(pathname) {
  if (!pathname || pathname === '*') {
    return '/not-found';
  }

  if (pathname.startsWith('/ministries/')) {
    return '/fellowship-ministries';
  }

  return pageIntentConfig[pathname] ? pathname : '/not-found';
}

export function getPageIntent(pathname, language) {
  const locale = normalizeLanguage(language);
  const routeKey = resolveRouteKey(pathname);
  return pageIntentConfig[routeKey][locale];
}
